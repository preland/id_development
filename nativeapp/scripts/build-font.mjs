// Reverse the bit order of a byte: bit 0 (LSB) <-> bit 7 (MSB), etc.
// Converts LSB-is-left rows (source table) into MSB-is-left rows (id reader).
function reverseByte(b) {
  let r = 0;
  for (let i = 0; i < 8; i++) {
    r = (r << 1) | (b & 1);
    b >>= 1;
  }
  return r & 0xff;
}

function charLabel(code) {
  const ch = String.fromCharCode(code);
  if (ch === "\\") return "\\\\";
  if (ch === "'") return "\\'";
  return ch;
}

function renderAscii(rowsMsbLeft) {
  return rowsMsbLeft
    .map((row) => {
      let line = "";
      for (let col = 7; col >= 0; col--) {
        line += (row & (1 << col)) ? "#" : ".";
      }
      return line;
    })
    .join("\n");
}

export function buildFontRows() {
  // Returns { rows: int[760] (MSB-is-left, top row first), byChar: Map<code, int[8]> }
  const rows = [];
  const byChar = new Map();
  for (let code = 0x20; code <= 0x7e; code++) {
    const src = FONT8X8_BASIC[code];
    if (!src) {
      throw new Error(`missing glyph data for char code ${code}`);
    }
    const glyph = src.map(reverseByte);
    byChar.set(code, glyph);
    for (const b of glyph) rows.push(b);
  }
  return { rows, byChar };
}

function emitIdSource(rows) {
  const lines = [];
  lines.push("// glyphs.gen.id -- GENERATED by scripts/build-font.mjs. Do not edit by hand.");
  lines.push("// 8x8 bitmap font, ASCII 32..126 (95 glyphs, 8 rows each, top row first).");
  lines.push("// Each int is one row; bit 128 = leftmost column, bit 1 = rightmost.");
  lines.push("");
  lines.push("font_data() {");
  lines.push("  export int[] glyphs = [");
  for (let code = 0x20; code <= 0x7e; code++) {
    const base = (code - 0x20) * 8;
    const glyphRows = rows.slice(base, base + 8);
    const isLast = code === 0x7e;
    const rowText = glyphRows.join(", ") + (isLast ? "" : ",");
    lines.push(`    ${rowText} // '${charLabel(code)}'`);
  }
  lines.push("  ];");
  lines.push("} return void;");
  lines.push("");
  return lines.join("\n");
}

function main() {
  const outArg = process.argv[2];
  const outPath = outArg
    ? path.resolve(process.cwd(), outArg)
    : path.resolve(__dirname, "../id/view/glyphs.gen.id");

  const { rows, byChar } = buildFontRows();

  if (rows.length !== 760) {
    throw new Error(`expected 760 ints, got ${rows.length}`);
  }
  for (const v of rows) {
    if (!Number.isInteger(v) || v < 0 || v > 255) {
      throw new Error(`row value out of range: ${v}`);
    }
  }

  const src = emitIdSource(rows);

  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, src, "utf8");

  console.log(`Wrote ${rows.length} ints to ${outPath}`);

  // ASCII-art preview for a few glyphs, to eyeball orientation.
  for (const ch of ["A", "g", "?", "1"]) {
    const code = ch.charCodeAt(0);
    const glyph = byChar.get(code);
    console.log(`\nPreview '${ch}' (code ${code}):`);
    console.log(renderAscii(glyph));
  }
}

main();
